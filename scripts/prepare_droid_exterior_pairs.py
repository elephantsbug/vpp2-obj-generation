#!/usr/bin/env python3
"""Prepare full-length, synchronized DROID RGB/object pairs for human review.

No temporal resampling: output frame i is source frame i in both cameras.
The playback FPS is a display time base, not an original capture timestamp.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ProcessPoolExecutor, as_completed
from fractions import Fraction
import hashlib
from itertools import zip_longest
import json
import os
from pathlib import Path

os.environ["CUDA_VISIBLE_DEVICES"] = ""
import av
import cv2
import numpy as np
from PIL import Image, ImageDraw, ImageFont


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def write_json(path, value):
    path = Path(path)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n")
    os.replace(temporary, path)


def masks_for(view, count):
    with np.load(view["segmentation_npz"], allow_pickle=False) as archive:
        raw = archive["masks"]
        if raw.shape != (1, count, 1, 180, 320):
            raise ValueError(f"Unexpected mask shape: {raw.shape}: {view['episode_name']}")
        if not np.all((raw == 0) | (raw == 1)):
            raise ValueError(f"Expected binary masks: {view['episode_name']}")
        result = np.asarray(raw[0, :, 0], dtype=np.bool_).copy()
    return result


def transform(rgb, mask):
    if rgb.shape != (180, 320, 3) or mask.shape != (180, 320):
        raise ValueError(f"Source geometry differs: {rgb.shape}, {mask.shape}")
    # Preserve16:9 within each224-square view; black49px padding above/below.
    resized = cv2.resize(rgb, (224, 126), interpolation=cv2.INTER_AREA)
    resized_mask = cv2.resize(mask.astype(np.uint8), (224, 126), interpolation=cv2.INTER_NEAREST).astype(bool)
    scene = np.zeros((224, 224, 3), dtype=np.uint8)
    obj = np.zeros_like(scene)
    scene[49:175] = resized
    obj[49:175] = np.where(resized_mask[..., None], resized, 0)
    return scene, obj, int(resized_mask.sum())


class VideoWriter:
    def __init__(self, path, fps):
        self.path = Path(path)
        self.temporary = self.path.with_name(self.path.stem + ".partial.mp4")
        self.container = av.open(str(self.temporary), mode="w", format="mp4", options={"movflags": "+faststart"})
        self.stream = self.container.add_stream("libx264", rate=fps)
        self.stream.width, self.stream.height = 448, 224
        self.stream.pix_fmt = "yuv420p"
        self.stream.options = {"crf": "16", "preset": "fast"}
        self.stream.codec_context.thread_count = 2
        self.fps = fps

    def write(self, array, index):
        frame = av.VideoFrame.from_ndarray(array, format="rgb24")
        frame.pts, frame.time_base = index, Fraction(1, self.fps)
        for packet in self.stream.encode(frame):
            self.container.mux(packet)

    def close(self):
        for packet in self.stream.encode():
            self.container.mux(packet)
        self.container.close()
        os.replace(self.temporary, self.path)

    def abort(self):
        self.container.close()
        self.temporary.unlink(missing_ok=True)


def contact_sheet(path, snapshots):
    font_path = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
    font = ImageFont.truetype(font_path, 16)
    canvas = Image.new("RGB", (448 * len(snapshots), 500), (242, 245, 249))
    draw = ImageDraw.Draw(canvas)
    for column, (index, (scene, obj)) in enumerate(sorted(snapshots.items())):
        x = column * 448
        draw.text((x + 8, 5), f"Frame {index} | ext1 LEFT / ext2 RIGHT", font=font, fill=(20, 30, 45))
        canvas.paste(Image.fromarray(scene), (x, 28))
        draw.text((x + 8, 254), "Object RGB on black", font=font, fill=(20, 30, 45))
        canvas.paste(Image.fromarray(obj), (x, 276))
    canvas.save(path)


def prepare_one(candidate, output, fps):
    cv2.setNumThreads(1)
    output = Path(output)
    folder = output / "episodes" / candidate["split"] / candidate["trajectory_id"]
    folder.mkdir(parents=True, exist_ok=True)
    record_path = folder / "pair.json"
    if record_path.exists():
        record = json.loads(record_path.read_text())
        if record["candidate_sha256"] != hashlib.sha256(json.dumps(candidate, sort_keys=True).encode()).hexdigest():
            raise ValueError(f"Existing candidate changed: {record_path}")
        if record["playback_fps"] != fps:
            raise ValueError("Existing FPS differs")
        if record.get("converter_sha256") != sha256(__file__):
            raise ValueError("Existing pair was generated by different converter code")
        for view in record["source_evidence"]:
            for evidence in view["files"].values():
                if sha256(evidence["path"]) != evidence["sha256"]:
                    raise ValueError(f"Existing source changed: {evidence['path']}")
        for field, digest in record["artifact_sha256"].items():
            if sha256(record[field]) != digest:
                raise ValueError(f"Existing artifact changed: {record[field]}")
        return record

    views = candidate["views"]
    if [view["camera_view"] for view in views] != ["exterior_image_1_left", "exterior_image_2_left"]:
        raise ValueError("Expected ordered external cameras1 then2")
    count = candidate["source_frame_count"]
    masks = [masks_for(view, count) for view in views]
    start, end = candidate["longest_common_segment_inclusive"]
    if not 0 <= start <= end < count:
        raise ValueError("Invalid preview interval")
    chosen = {start, (start + end) // 2, end}
    valid = np.zeros(count, dtype=bool)
    for a, b in candidate["common_valid_segments_inclusive"]:
        valid[a:b + 1] = True
    if not all(np.all(mask[valid].reshape(valid.sum(), -1).any(axis=1)) for mask in masks):
        raise ValueError("Empty source mask inside declared jointly valid interval")

    paths = {"condition_video_path": folder / "full_scene_rgb.mp4", "target_video_path": folder / "object_rgb.mp4",
             "preview_path": folder / "preview.png", "frame_index_path": folder / "frame_index.npz"}
    sources = [av.open(view["primary_video"]) for view in views]
    writers = [VideoWriter(paths["condition_video_path"], fps), VideoWriter(paths["target_video_path"], fps)]
    source_metadata, source_pts = [], [[], []]
    snapshots, areas = {}, np.zeros((count, 2), dtype=np.int64)
    try:
        for source in sources:
            if len(source.streams.video) != 1:
                raise ValueError("Expected exactly one source video stream")
            stream = source.streams.video[0]
            stream.thread_count = 1
            if (stream.width, stream.height) != (320, 180):
                raise ValueError("Unexpected source resolution")
            source_metadata.append({"width": stream.width, "height": stream.height,
                                    "encoded_fps": str(stream.average_rate), "time_base": str(stream.time_base)})
        decoded = 0
        for i, frames in enumerate(zip_longest(*(source.decode(video=0) for source in sources))):
            if any(frame is None for frame in frames) or i >= count:
                raise ValueError("Source video frame counts differ or exceed manifest")
            scene_parts, object_parts = [], []
            for view_index, frame in enumerate(frames):
                source_pts[view_index].append(float(frame.time) if frame.time is not None else None)
                scene, obj, area = transform(frame.to_ndarray(format="rgb24"), masks[view_index][i])
                scene_parts.append(scene)
                object_parts.append(obj)
                areas[i, view_index] = area
            scene, obj = np.concatenate(scene_parts, axis=1), np.concatenate(object_parts, axis=1)
            writers[0].write(scene, i)
            writers[1].write(obj, i)
            if i in chosen:
                snapshots[i] = (scene.copy(), obj.copy())
            decoded += 1
        if decoded != count or not np.allclose(source_pts[0], source_pts[1], rtol=0, atol=1e-6):
            raise ValueError("Source frame count or encoded PTS alignment differs")
        if not np.all(areas[valid] > 0):
            raise ValueError("Empty resized mask in a valid interval")
        for writer in writers:
            writer.close()
    except BaseException:
        for writer in writers:
            try:
                writer.abort()
            except Exception:
                pass
        raise
    finally:
        for source in sources:
            source.close()

    contact_sheet(paths["preview_path"], snapshots)
    np.savez_compressed(paths["frame_index_path"], source_frame_indices=np.arange(count, dtype=np.int64),
                        display_timestamps_us=np.rint(np.arange(count) * 1e6 / fps).astype(np.int64),
                        source_encoded_pts_seconds=np.asarray(source_pts, dtype=np.float64),
                        shared_valid_mask_frames=valid, resized_foreground_pixels_by_view=areas)
    source_evidence = []
    for view, metadata in zip(views, source_metadata):
        source_evidence.append({"camera_view": view["camera_view"], "episode_name": view["episode_name"],
                                **metadata, "files": {key: {"path": str(Path(view[key]).resolve()), "sha256": sha256(view[key])}
                                                      for key in ("primary_video", "segmentation_npz", "parquet")}})
    record = {"schema_version": "droid_exterior_pairs_review_v1", "trajectory_id": candidate["trajectory_id"],
              "split": candidate["split"], "rank_in_split": candidate["rank_in_split"],
              "instruction_hint": candidate["instruction_hint"], "instruction_status": "original_hint_not_final_training_prompt",
              "action_category": candidate.get("action_category"),
              "view1_episode_name": views[0]["episode_name"], "view2_episode_name": views[1]["episode_name"],
              "frame_count": count, "width": 448, "height": 224, "playback_fps": fps,
              "native_sampling_hz_nominal": 15, "temporal_resampling": False, "source_frame_mapping": "identity_0_through_N_minus_1",
              "timing_note": "Display PTS uses nominal15Hz; original capture timestamps are not inferred from source10fps MP4 PTS.",
              "spatial_transform": {"per_view_source_hw": [180, 320], "per_view_resized_hw": [126, 224],
                                    "per_view_output_hw": [224, 224], "padding_top_bottom_left_right": [49, 49, 0, 0],
                                    "rgb_resize": "cv2.INTER_AREA", "mask_resize": "cv2.INTER_NEAREST",
                                    "object_composition": "resized_uint8_RGB_where_nearest_resized_mask_else_zero",
                                    "view_order": ["exterior_image_1_left", "exterior_image_2_left"]},
              "codec": {"name": "libx264", "pixel_format": "yuv420p", "crf": 16, "preset": "fast"},
              "quality": {"shared_valid_segments_inclusive": candidate["common_valid_segments_inclusive"],
                          "validity_source": "historical_tier_a_002_intersection_plus_current_nonempty_checks",
                          "human_target_consistency_review": "pending", "shared_valid_frame_count": int(valid.sum()),
                          "full_video_empty_mask_frames_by_view": (areas == 0).sum(axis=0).tolist()},
              "selected_review_start": start, "selected_review_end": end,
              "source_evidence": source_evidence,
              "converter_sha256": sha256(__file__),
              "candidate_sha256": hashlib.sha256(json.dumps(candidate, sort_keys=True).encode()).hexdigest(),
              **{key: str(path.resolve()) for key, path in paths.items()}}
    record["artifact_sha256"] = {key: sha256(path) for key, path in paths.items()}
    write_json(record_path, record)
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidates", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--train-count", type=int, default=20)
    parser.add_argument("--val-count", type=int, default=5)
    parser.add_argument("--workers", type=int, default=2)
    parser.add_argument("--playback-fps", type=int, default=15)
    args = parser.parse_args()
    if min(args.train_count, args.val_count, args.workers, args.playback_fps) <= 0:
        parser.error("Counts, workers and FPS must be positive")
    source = json.loads(args.candidates.read_text())
    candidates = source["candidates"]
    selected = []
    for split, count in (("train", args.train_count), ("val", args.val_count)):
        rows = sorted((row for row in candidates if row["split"] == split), key=lambda row: row["rank_in_split"])
        if len(rows) < count:
            raise ValueError(f"Not enough {split} candidates")
        selected.extend(rows[:count])
    if len({row["trajectory_id"] for row in selected}) != len(selected):
        raise ValueError("Duplicate or split-overlapping trajectories")
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=True)
    selection = {**source, "candidates": selected, "candidate_file_sha256": sha256(args.candidates)}
    if (output / "selection.json").exists() and json.loads((output / "selection.json").read_text()) != selection:
        raise ValueError("Output has a different frozen selection")
    write_json(output / "selection.json", selection)
    write_json(output / "status.json", {"status": "running", "total": len(selected), "completed": 0})
    results = []
    try:
        with ProcessPoolExecutor(max_workers=args.workers) as pool:
            futures = {pool.submit(prepare_one, row, output, args.playback_fps): row for row in selected}
            for future in as_completed(futures):
                record = future.result()
                results.append(record)
                write_json(output / "status.json", {"status": "running", "total": len(selected), "completed": len(results)})
                print(json.dumps({"completed": len(results), "total": len(selected), "trajectory": record["trajectory_id"],
                                  "frames": record["frame_count"], "split": record["split"]}), flush=True)
    except BaseException as error:
        write_json(output / "status.json", {"status": "failed", "completed": len(results), "error": str(error)})
        raise
    results.sort(key=lambda row: (row["split"] != "train", row["rank_in_split"]))
    for name, rows in (("pairs.jsonl", results), ("train_pairs.jsonl", [r for r in results if r["split"] == "train"]),
                       ("val_pairs.jsonl", [r for r in results if r["split"] == "val"])):
        (output / name).write_text("".join(json.dumps(row, ensure_ascii=False, allow_nan=False) + "\n" for row in rows))
    write_json(output / "status.json", {"status": "complete", "total": len(selected), "completed": len(results),
                                       "total_source_frames": sum(row["frame_count"] for row in results),
                                       "manifest_sha256": sha256(output / "pairs.jsonl"), "human_review": "pending"})


if __name__ == "__main__":
    main()
